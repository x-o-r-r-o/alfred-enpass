function setupItem(error) {
  const icons = { install: "warning", config: "settings", setpassword: "unlock", badpassword: "lock", error: "warning" }
  const item = {
    title: error.message,
    subtitle: error.subtitle || "",
    valid: false,
    icon: { path: "icons/" + (icons[error.kind] || "warning") + ".png" },
  }
  if (error.kind === "install") {
    Object.assign(item, { valid: true, arg: "brew install enpass-cli", variables: { action: "copy_text", text: "brew install enpass-cli" } })
  } else if (error.kind === "config") {
    Object.assign(item, { valid: true, arg: "configure", variables: { action: "configure" } })
    item.subtitle = item.subtitle ? item.subtitle : "↩ Open the Workflow’s Configuration"
  } else if (error.kind === "setpassword" || error.kind === "badpassword") {
    Object.assign(item, { valid: true, arg: "setpassword", variables: { action: "setpassword" } })
  }
  return item
}

function listEntries() {
  let vault = null
  try {
    const unlocked = unlock()
    vault = unlocked.vault
    const entries = runCli(vault, unlocked.password, "list")
    const items = entries
      .map((entry) => ({ ...entry, fields: entry.fields || [] }))
      .sort((a, b) => (a.title || "").localeCompare(b.title || "", undefined, { sensitivity: "base" })
        || usernameOf(a).localeCompare(usernameOf(b)))
      .map(entryItem)
    if (items.length === 0) {
      items.push({ title: "No entries in " + vault.name, subtitle: "Add items in Enpass", valid: false, icon: { path: "icon.png" } })
    }
    return {
      items: [...items, ...utilityItems(vault)],
      // Alfred keeps these rows (titles, usernames, websites; never secrets) in memory for a minute
      cache: { seconds: 60, loosereload: true },
    }
  } catch (error) {
    if (!(error instanceof SetupError)) throw error
    if (error.kind === "badpassword") {
      // Recover the vault so "Forget Master Password" stays available
      try { vault = loadVault() } catch (e) { vault = null }
    }
    return { skipknowledge: true, items: [setupItem(error), ...utilityItems(vault)] }
  }
}

// ─── Script Filter: fields of one entry ─────────────────────────────────────

function listFields() {
  const uuid = envVar("entry_uuid")
  const title = envVar("entry_title")
  const back = {
    title: "Back to Search",
    subtitle: "Return to all entries",
    match: "back return search",
    arg: "back",
    icon: { path: "icons/back.png" },
    variables: { action: "back" },
  }
  try {
    const { vault, password } = unlock()
    const entry = findEntry(vault, password, uuid, title, "list")
    const mode = config.defaultAction
    const base = { entry_uuid: uuid, entry_title: title }
    let section = ""
    const items = []
    entry.fields.forEach((field, index) => {
      // Types starting with "." are Enpass's own metadata (linked Android apps, 2FA hints)
      if (isMetadata(field)) return
      if (field.type === "section") {
        section = field.label || ""
        return
      }
      const label = fieldLabel(field)
      const isURL = field.type === "url"
      const secret = isSecret(field)
      const value = secret
        ? (field.type === "totp" ? "Current code" : MASK)
        : isURL && hasCredentials(normalizeURL(field.value || "")) ? displayURL(normalizeURL(field.value))
        : (field.value || "").replace(/\s*\n\s*/g, " ⏎ ")
      const vars = { ...base, action: "field", field_index: String(index), field_type: field.type, field_label: label, field_secret: secret ? "1" : "0" }
      const item = {
        title: label,
        subtitle: [section, value].filter(Boolean).join(" › "),
        arg: String(index),
        match: [label, section, secret ? "" : value, field.type].filter(Boolean).join(" "),
        icon: { path: fieldIcon(field) },
        variables: { ...vars, mode },
        mods: {
          cmd: { valid: true, subtitle: actionVerb(otherMode(mode)) + " " + label.toLowerCase(), variables: { ...vars, mode: otherMode(mode) } },
          ctrl: isURL && normalizeURL(field.value || "")
            ? { valid: true, subtitle: "Open " + displayURL(normalizeURL(field.value)), arg: normalizeURL(field.value), variables: { ...vars, action: "open_field" } }
            : { valid: false, subtitle: "Not a web address" },
        },
      }
      if (!secret && field.value) item.text = { copy: field.value, largetype: field.value }
      items.push(item)
    })
    if (items.length === 0) {
      items.push({ title: "This entry has no fields", subtitle: entry.title, valid: false, icon: { path: "icons/fields.png" } })
    }
    return { skipknowledge: true, items: [...items, back] }
  } catch (error) {
    if (!(error instanceof SetupError)) throw error
    return { skipknowledge: true, items: [setupItem(error), back] }
  }
}

function fieldIcon(field) {
  if (field.type === "totp") return "icons/totp.png"
  if (field.type === "url") return "icons/url.png"
  if (field.type === "username" || field.type === "email") return "icons/username.png"
  if (field.type === "password") return "icons/password.png"
  if (field.type.startsWith("cc")) return "icons/creditcard.png"
  if (isSecret(field)) return "icons/secret.png"
  return "icons/text.png"
}

// ─── Actions ────────────────────────────────────────────────────────────────

// Output for the Run Script: arg becomes the notification text (empty = no notification)
function notify(title, text = "") {
  return JSON.stringify({ alfredworkflow: { arg: text || title, variables: { notif_title: title } } })
}

function silent() {
  return JSON.stringify({ alfredworkflow: { arg: "", variables: { notif_title: "" } } })
}

function writeSecretToClipboard(value) {
  const pasteboard = $.NSPasteboard.generalPasteboard
  // Current host only: keeps secrets off Universal Clipboard (Handoff to other devices)
  pasteboard.prepareForNewContentsWithOptions($.NSPasteboardContentsCurrentHostOnly)
  pasteboard.setStringForType($(value), $.NSPasteboardTypeString)
  for (const type of PRIVATE_PASTEBOARD_TYPES) pasteboard.setStringForType($(""), $(type))
  return Number(pasteboard.changeCount)
}

function pasteIntoFrontmostApp() {
  if (config.dryRun) return
  delay(0.1)
  Application("System Events").keystroke("v", { using: "command down" })
}

// Clears the clipboard later, in a detached process, only if nothing else was copied meanwhile
function scheduleClear(changeCount) {
  if (config.clearAfter <= 0) return
  // Alfred runs scripts from the workflow folder
  const script = $.NSFileManager.defaultManager.currentDirectoryPath.js + "/enpass.js"
  const task = $.NSTask.alloc.init
  task.executableURL = $.NSURL.fileURLWithPath("/bin/sh")
  task.arguments = $(["-c", 'sleep "$1" && exec /usr/bin/osascript -l JavaScript "$2" clear "$3"', "sh",
    String(config.clearAfter), script, String(changeCount)])
  task.standardInput = $.NSFileHandle.fileHandleWithNullDevice
  task.standardOutput = $.NSFileHandle.fileHandleWithNullDevice
  task.standardError = $.NSFileHandle.fileHandleWithNullDevice
  task.launchAndReturnError($())
}

function clearClipboard(expectedCount) {
  const pasteboard = $.NSPasteboard.generalPasteboard
  if (String(pasteboard.changeCount) === String(expectedCount)) pasteboard.clearContents
}

function deliver(value, mode, what) {
  const count = writeSecretToClipboard(value)
  // Schedule clearing first, so the secret doesn't stay on the clipboard if pasting fails
  scheduleClear(count)
  if (mode === "paste") {
    try {
      pasteIntoFrontmostApp()
    } catch (e) {
      return notify("Copied " + what + " but couldn’t paste",
        "Allow Alfred in System Settings → Privacy & Security → Accessibility.")
    }
  }
  const done = mode === "paste" ? "Pasted " : "Copied "
  const clears = config.clearAfter > 0 ? " Clipboard clears in " + config.clearAfter + " s." : ""
  // Entry titles stay out of notifications: Notification Center keeps them and may show them on the lock screen
  return notify(done + what, clears.trim() || "Clipboard won’t be cleared automatically.")
}

function openURL(url) {
  url = normalizeURL(url || "")
  if (!url) return notify("No website to open")
  if (!config.dryRun) {
    const nsurl = $.NSURL.URLWithString($(url))
    if (nsurl.isNil() || !$.NSWorkspace.sharedWorkspace.openURL(nsurl)) return notify("Could not open website", displayURL(url))
  }
  return silent()
}

// Resolves a field by index and checks its type (and label, when known) still match what the row showed
function fieldAt(entry, index, type, label = envVar("field_label")) {
  const field = entry.fields[Number(index)]
  if (!field || (type && field.type !== type) || (label && fieldLabel(field) !== label)) {
    throw new SetupError("error", "Entry changed", "Search again to see its current fields")
  }
  return field
}

// Codes use the standard 30-second period (enpass-cli computes them the same way)
function totpValue(vault, password, uuid, title, index) {
  const windowBefore = Math.floor(Date.now() / 30000)
  let field = fieldAt(findEntry(vault, password, uuid, title, "show"), index, "totp")
  const now = Date.now() / 1000
  const remaining = 30 - now % 30
  // The code may have been computed in a window that has since ended, or be about to expire:
  // wait for the next window if needed and read it again
  if (!field.totp_error && (Math.floor(now / 30) !== windowBefore || remaining <= 3)) {
    if (remaining <= 3) delay(remaining + 0.2)
    field = fieldAt(findEntry(vault, password, uuid, title, "show"), index, "totp")
  }
  if (field.totp_error || !field.totp_code) {
    throw new SetupError("error", "Could not generate the one-time code", "The TOTP secret in Enpass looks invalid")
  }
  return field.totp_code
}

// Asks for the master password; in dry-run mode (tests) the answer comes from the environment.
// Returns null when cancelled.
function askPassword(message) {
  if (config.dryRun) return envVar("enpass_test_answer")
  const app = Application.currentApplication()
  app.includeStandardAdditions = true
  try {
    app.activate()
    return app.displayDialog(message, {
      withTitle: "Enpass for Alfred",
      defaultAnswer: "",
      hiddenAnswer: true,
      buttons: ["Cancel", "Unlock"],
      defaultButton: "Unlock",
      cancelButton: "Cancel",
      withIcon: Path($.NSFileManager.defaultManager.currentDirectoryPath.js + "/icon.png"),
    }).textReturned
  } catch (e) {
    if (e.errorNumber === -128) return null
    throw e
  }
}

function setPassword() {
  const vault = loadVault()
  let message = "Enter the master password for your “" + vault.name + "” Enpass vault.\n\nIt’s stored in your macOS Keychain and only used to read the vault."
  for (let attempt = 0; attempt < 3; attempt++) {
    const password = askPassword(message)
    if (password === null) return silent()
    if (!password) {
      message = "The master password can’t be empty. Try again."
      continue
    }
    const check = exec(vault.cli, cliArgs(vault, "dryrun"), { env: { MASTERPW: password } })
    if (check.status !== 0) {
      const error = cliError(check)
      if (error.kind !== "badpassword") return notify(error.message, error.subtitle)
      message = "That master password didn’t unlock “" + vault.name + "”. Try again."
      continue
    }
    if (!savePassword(vault, password)) return notify("Could not save to the Keychain", "The master password was correct but couldn’t be stored")
    reopenSearch()
    return notify("Vault unlocked", "Master password saved in your Keychain")
  }
  return notify("Vault not unlocked", "The master password was wrong three times")
}

function reopenSearch() {
  if (config.dryRun) return
  Application("com.runningwithcrayons.Alfred").search(config.keyword + " ")
}

// Text or a URL from the Universal Action: search for the website's domain, or the text as is
function searchTerm(input) {
  const text = (input || "").trim()
  const host = hostOf(text)
  return (host || text).replace(/\s+/g, " ")
}

function act(input) {
  const action = envVar("action")
  const uuid = envVar("entry_uuid")
  const title = envVar("entry_title")
  const mode = envVar("mode", config.defaultAction) === "paste" ? "paste" : "copy"
  try {
    switch (action) {
      case "setpassword":
        return setPassword()
      case "forget": {
        const vault = loadVault()
        return deletePassword(vault)
          ? notify("Master password forgotten", "Removed from your Keychain")
          : notify("Nothing to forget", "No master password was saved for this vault")
      }
      case "configure":
        if (!config.dryRun) Application("com.runningwithcrayons.Alfred").revealWorkflow(config.bundleId, { configuration: true })
        return silent()
      case "open_enpass":
        if (!config.dryRun) Application(ENPASS_BUNDLE_ID).activate()
        return silent()
      case "back":
        reopenSearch()
        return silent()
      case "search":
        if (!config.dryRun) Application("com.runningwithcrayons.Alfred").search(config.keyword + " " + searchTerm(input))
        return silent()
      case "copy_text": {
        // Plain, non-secret text (e.g. the install command) goes to the clipboard normally
        const pasteboard = $.NSPasteboard.generalPasteboard
        pasteboard.clearContents
        pasteboard.setStringForType($(envVar("text")), $.NSPasteboardTypeString)
        return notify("Copied", envVar("text"))
      }
    }

    const { vault, password } = unlock()
    switch (action) {
      case "field": {
        const index = envVar("field_index")
        const type = envVar("field_type")
        if (type === "totp") return deliver(totpValue(vault, password, uuid, title, index), mode, "one-time code")
        // Non-secret fields come from `list`, so nothing is decrypted for them
        const secret = SECRET_TYPES.has(type) || envVar("field_secret") === "1"
        let field = fieldAt(findEntry(vault, password, uuid, title, secret ? "show" : "list"), index, type)
        if (!secret && isSecret(field)) field = fieldAt(findEntry(vault, password, uuid, title, "show"), index, type)
        if (!field.value) return notify(fieldLabel(field) + " is empty")
        return deliver(field.value, mode, fieldLabel(field).toLowerCase())
      }
      case "username": {
        const username = usernameOf(findEntry(vault, password, uuid, title, "list"))
        if (!username) return notify("No username")
        return deliver(username, mode, "username")
      }
      case "url":
        return openURL(urlOf(findEntry(vault, password, uuid, title, "list")))
      case "open_field": {
        const field = fieldAt(findEntry(vault, password, uuid, title, "list"), envVar("field_index"), "url")
        return openURL(normalizeURL(field.value || ""))
      }
      default:
        return notify("Unknown action", action || "(none)")
    }
  } catch (error) {
    if (!(error instanceof SetupError)) throw error
    if (error.kind === "setpassword" || error.kind === "badpassword") return setPassword()
    return notify(error.message, error.subtitle)
  }
}

// ─── Entry point ────────────────────────────────────────────────────────────

function run(argv) {
  const mode = argv[0]
  switch (mode) {
    case "list":
      return JSON.stringify(listEntries())
    case "fields":
      return JSON.stringify(listFields())
    case "act":
      return act(argv[1])
    case "clear":
      clearClipboard(argv[1])
      return ""
    default:
      return JSON.stringify({ items: [{ title: "Unknown mode: " + mode, valid: false }] })
  }
}
