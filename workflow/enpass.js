class SetupError extends Error {
  // kind picks the icon and action of the row shown in Alfred
  constructor(kind, title, subtitle, extra = {}) {
    super(title)
    this.kind = kind
    this.subtitle = subtitle
    this.extra = extra
  }
}

// ─── Vault ──────────────────────────────────────────────────────────────────

function readJSON(path) {
  const data = $.NSData.dataWithContentsOfFile(path)
  if (data.isNil()) return null
  try {
    return JSON.parse($.NSString.alloc.initWithDataEncoding(data, $.NSUTF8StringEncoding).js)
  } catch (e) {
    return null
  }
}

function loadVault() {
  const cli = findCli()
  if (!cli) {
    if (config.cliPath) {
      throw new SetupError("config", "enpass-cli not found at the configured path",
        config.cliPath + " — fix it in the Workflow’s Configuration")
    }
    throw new SetupError("install", "Install enpass-cli to use this workflow",
      "↩ Copy the install command: brew install enpass-cli")
  }
  if (!fileExists(config.vaultPath, true)) {
    throw new SetupError("config", "Enpass vault folder not found",
      config.vaultPath + " — set it in the Workflow’s Configuration")
  }
  const info = readJSON(config.vaultPath + "/vault.json")
  if (!info || !fileExists(config.vaultPath + "/vault.enpassdb")) {
    throw new SetupError("config", "Not an Enpass vault folder",
      "Expected vault.json and vault.enpassdb in " + config.vaultPath)
  }
  const needsKeyfile = Number(info.have_keyfile) === 1
  if (needsKeyfile && !config.keyfilePath) {
    throw new SetupError("config", "This vault needs a keyfile",
      "Choose your Enpass keyfile in the Workflow’s Configuration")
  }
  if (needsKeyfile && !fileExists(config.keyfilePath)) {
    throw new SetupError("config", "Keyfile not found", config.keyfilePath)
  }
  return {
    cli,
    name: String(info.vault_name || "Enpass"),
    account: String(info.vault_uuid || config.vaultPath),
    // enpass-cli refuses a keyfile the vault doesn't use, so only pass it when needed
    keyfile: needsKeyfile ? config.keyfilePath : "",
  }
}

function cliArgs(vault, command, filters = []) {
  const args = ["-vault", config.vaultPath]
  if (vault.keyfile) args.push("-keyfile", vault.keyfile)
  args.push("-nonInteractive", "-log", "error", "-json", "-detailed")
  if (config.showTrashed) args.push("-trashed")
  // Filters are positional; flag parsing stops at the command, so filters starting with "-" are safe
  return [...args, command, ...filters]
}

// Runs enpass-cli with the master password in its environment and returns the parsed entries
function runCli(vault, password, command, filters = []) {
  const result = exec(vault.cli, cliArgs(vault, command, filters), { env: { MASTERPW: password }, timeout: CLI_TIMEOUT })
  if (result.timedOut) throw new SetupError("error", "enpass-cli took too long", "Try again, or check that the vault isn’t locked by another app")
  if (result.status === 0) {
    try {
      const entries = JSON.parse(result.out || "[]")
      if (!Array.isArray(entries)) return []
      // Normalise what the rest of the script relies on
      return entries.filter((e) => e && typeof e.uuid === "string").map((e) => ({
        ...e,
        title: String(e.title || ""),
        subtitle: String(e.subtitle || ""),
        fields: (Array.isArray(e.fields) ? e.fields : []).map((f) => ({ ...f, type: String(f.type || "text"), label: String(f.label || ""), value: f.value === undefined ? undefined : String(f.value) })),
      }))
    } catch (e) {
      throw new SetupError("error", "Unexpected output from enpass-cli", "Try updating it: brew upgrade enpass-cli")
    }
  }
  throw cliError(result)
}

// Turns an enpass-cli failure into a row that tells the user what to do. Never includes secrets.
function cliError(result) {
  const message = (result.err.match(/msg="([^"]*)"/) || [])[1] || result.err.trim().split("\n").pop() || ""
  const detail = (result.err.match(/error="([^"]*)"/) || [])[1] || ""
  const text = (message + " " + detail).toLowerCase()
  if (text.includes("could not open vault") || text.includes("file is not a database") || text.includes("could not generate database key")) {
    if (text.includes("keyfile")) {
      return new SetupError("config", "Could not read the keyfile", detail || message)
    }
    return new SetupError("badpassword", "Wrong master password or keyfile",
      "↩ Enter the master password again")
  }
  if (text.includes("keyfile")) return new SetupError("config", "Keyfile problem", detail || message)
  return new SetupError("error", "enpass-cli failed", (message + (detail ? ": " + detail : "")).trim() || "Exit code " + result.status)
}

// ─── Keychain ───────────────────────────────────────────────────────────────
// The master password is stored base64-encoded (security -w hex-encodes non-ASCII values),
// written through `security -i` on stdin so it never appears in a process list.

function keychainService() {
  return config.keychainService || config.bundleId
}

function base64Encode(text) {
  return $(text).dataUsingEncoding($.NSUTF8StringEncoding).base64EncodedStringWithOptions(0).js
}

function base64Decode(text) {
  const data = $.NSData.alloc.initWithBase64EncodedStringOptions($(text.trim()), 0)
  if (data.isNil()) return null
  return $.NSString.alloc.initWithDataEncoding(data, $.NSUTF8StringEncoding).js ?? null
}

function quoteForSecurity(text) {
  // A newline would end the `security -i` command line and start another, so drop control characters
  const clean = String(text).replace(/[\u0000-\u001f\u007f]/g, " ")
  return '"' + clean.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"'
}

function getPassword(vault) {
  const result = exec("/usr/bin/security", ["find-generic-password", "-s", keychainService(), "-a", vault.account, "-w"])
  if (result.status === 44) return null // not found
  if (result.status !== 0) {
    throw new SetupError("error", "Could not read the master password from the Keychain",
      "Allow access when macOS asks, or unlock your login keychain")
  }
  const password = base64Decode(result.out)
  if (password === null) throw new SetupError("badpassword", "Stored master password is unreadable", "↩ Enter it again")
  return password
}

function savePassword(vault, password) {
  const label = "Enpass for Alfred (" + vault.name.slice(0, 80) + ")"
  const command = ["add-generic-password", "-U",
    "-s", quoteForSecurity(keychainService()),
    "-a", quoteForSecurity(vault.account),
    "-l", quoteForSecurity(label),
    "-j", quoteForSecurity("Master password for the Enpass vault, base64-encoded"),
    "-w", quoteForSecurity(base64Encode(password))].join(" ")
  const result = exec("/usr/bin/security", ["-i"], { input: command + "\n" })
  // security -i exits 0 even when a command fails, so read the password back to confirm
  return result.status === 0 && getPassword(vault) === password
}

function deletePassword(vault) {
  const result = exec("/usr/bin/security", ["delete-generic-password", "-s", keychainService(), "-a", vault.account])
  return result.status === 0
}

// Returns the vault and a working master password, or throws a SetupError
function unlock() {
  const vault = loadVault()
  const password = getPassword(vault)
  if (password === null) {
    throw new SetupError("setpassword", "Unlock " + vault.name + " vault",
      "↩ Enter your Enpass master password (saved in your macOS Keychain)")
  }
  return { vault, password }
}

// ─── Entry helpers ──────────────────────────────────────────────────────────

function isSecret(field) {
  return Boolean(field.sensitive) || SECRET_TYPES.has(field.type)
}

function fieldLabel(field) {
  if (field.label && field.label.trim()) return field.label.trim()
  return TYPE_LABELS[field.type] || field.type.charAt(0).toUpperCase() + field.type.slice(1)
}

function usernameOf(entry) {
  const field = entry.fields.find((f) => f.type === "username" && f.value)
    || entry.fields.find((f) => f.type === "email" && f.value)
  return field ? field.value : ""
}

// The field ↩ copies: the first password, otherwise the first sensitive field (e.g. a card number)
function isMetadata(field) {
  return field.type.startsWith(".")
}

function primaryFieldIndex(entry) {
  const password = entry.fields.findIndex((f) => f.type === "password")
  if (password >= 0) return password
  return entry.fields.findIndex((f) => isSecret(f) && f.type !== "totp" && !isMetadata(f))
}

function totpFieldIndex(entry) {
  return entry.fields.findIndex((f) => f.type === "totp")
}

function urlOf(entry) {
  const field = entry.fields.find((f) => f.type === "url" && normalizeURL(f.value || ""))
  return field ? normalizeURL(field.value) : ""
}

// Web address to open, or "" when the value isn't one. Other schemes (file://, smb://, app links)
// are never opened: imported or shared vault data shouldn't be able to launch apps or mount shares.
function normalizeURL(value) {
  const url = value.trim()
  if (!url || /\s/.test(url)) return ""
  if (/^https?:\/\//i.test(url)) return url
  if (/^[a-z][a-z0-9+.-]*:/i.test(url) && !/^[^:/]+:\d+(\/|$)/.test(url)) return ""
  return "https://" + url
}

// For display only: scheme, host and path, without a login ("user:pass@") or query string
function displayURL(url) {
  const match = url.match(/^([a-z][a-z0-9+.-]*:\/\/)(?:[^@/?#]*@)?([^?#]*)/i)
  return match ? match[1] + match[2] : ""
}

function hasCredentials(url) {
  return /^[a-z][a-z0-9+.-]*:\/\/[^/?#]*@/i.test(url)
}

function hostOf(url) {
  const match = url.match(/^[a-z][a-z0-9+.-]*:\/\/([^/?#:]+)/i)
  return match ? match[1].replace(/^www\./i, "") : ""
}

function categoryName(category) {
  if (!category) return ""
  const names = { creditcard: "Credit Card", wifi: "Wi-Fi", misc: "Miscellaneous" }
  return names[category.toLowerCase()] || category.charAt(0).toUpperCase() + category.slice(1)
}

function categoryIcon(category) {
  return "icons/" + (CATEGORY_ICONS[(category || "").toLowerCase()] || "login") + ".png"
}

function actionVerb(mode) {
  return mode === "paste" ? "Paste" : "Copy"
}

function otherMode(mode) {
  return mode === "paste" ? "copy" : "paste"
}

// enpass-cli matches filters case-insensitively against title and username with SQLite's lower(),
// which only folds ASCII. So filter on the longest plain ASCII word, e.g. "Bank" from "Bank of Ümlaut 🏦".
// Characters SQLite's lower() and enpass-cli's Go lowercasing agree on: ASCII, and characters without
// case (digits, CJK, emoji…). Returns the longest run of them, e.g. "mlaut 🏦" from "Bank of Ümlaut 🏦".
function filterTerm(text) {
  const runs = Array.from(text || "")
    .map((c) => (c.charCodeAt(0) < 128 || c.toLowerCase() === c.toUpperCase() ? c : "\n"))
    .join("")
    .split("\n")
    .map((run) => run.trim())
    .filter(Boolean)
  return runs.sort((a, b) => b.length - a.length)[0] || ""
}

// Finds an entry by UUID while decrypting as little as possible: `show` (which decrypts secrets)
// only ever runs with a filter, unless the entry has no plain ASCII word in its title or username.
function findEntry(vault, password, uuid, title, command) {
  const found = (entries) => entries.find((e) => e.uuid === uuid)
  const tried = new Set()
  const attempt = (term) => {
    if (!term || tried.has(term.toLowerCase())) return null
    tried.add(term.toLowerCase())
    return found(runCli(vault, password, command, [term]))
  }
  let entry = attempt(filterTerm(title))
  if (!entry) {
    // Look the entry up without secrets to learn its current title and username (it may have been renamed)
    const listed = found(runCli(vault, password, "list"))
    if (!listed) throw new SetupError("error", "Entry not found", "It may have been deleted or renamed in Enpass")
    listed.fields = listed.fields || []
    if (command === "list") entry = listed
    else entry = attempt(filterTerm(listed.title)) || attempt(filterTerm(usernameOf(listed)))
    // Never decrypt the whole vault to find one entry
    if (!entry) throw new SetupError("error", "Can’t read this entry from Alfred",
      "Its title and username can’t be searched by enpass-cli. Copy it in Enpass, or add a plain word to its title")
  }
  if (!entry) throw new SetupError("error", "Entry not found", "It may have been deleted or renamed in Enpass")
  entry.fields = entry.fields || []
  return entry
}

// ─── Script Filter: entries ─────────────────────────────────────────────────

function entryItem(entry) {
  const username = usernameOf(entry)
  const url = urlOf(entry)
  const primary = primaryFieldIndex(entry)
  const totp = totpFieldIndex(entry)
  const title = entry.title || "(untitled)"
  const base = { entry_uuid: entry.uuid, entry_title: entry.title || "" }
  const mode = config.defaultAction
  const primaryLabel = primary >= 0 ? fieldLabel(entry.fields[primary]).toLowerCase() : ""
  const fieldVars = (index) => ({ action: "field", field_index: String(index), field_type: entry.fields[index].type, field_label: fieldLabel(entry.fields[index]), field_secret: isSecret(entry.fields[index]) ? "1" : "0" })
  // Enpass's own subtitle (e.g. "•••• 4242" for cards) when there's no username
  const subtitleParts = [username || (entry.subtitle || "").trim(), categoryName(entry.category)].filter(Boolean)
  if (entry.trashed) subtitleParts.unshift("In Trash")
  const hosts = entry.fields.filter((f) => f.type === "url" && f.value).map((f) => hostOf(normalizeURL(f.value))).filter(Boolean)

  const item = {
    uid: entry.uuid,
    title,
    subtitle: subtitleParts.join(SEP),
    arg: entry.uuid,
    match: [title, username, categoryName(entry.category), ...hosts].filter(Boolean).join(" "),
    autocomplete: title,
    icon: { path: entry.trashed ? "icons/trash.png" : categoryIcon(entry.category) },
    text: { copy: username || title, largetype: title },
    variables: primary >= 0
      ? { ...base, ...fieldVars(primary), mode }
      : { ...base, action: "fields" },
    mods: {
      cmd: username
        ? { valid: true, subtitle: actionVerb(mode) + " username: " + username, variables: { ...base, action: "username", mode } }
        : { valid: false, subtitle: "No username" },
      alt: totp >= 0
        ? { valid: true, subtitle: actionVerb(mode) + " one-time code", variables: { ...base, ...fieldVars(totp), mode } }
        : { valid: false, subtitle: "No one-time code" },
      ctrl: url
        ? { valid: true, subtitle: "Open " + displayURL(url), arg: url, variables: { ...base, action: "url" } }
        : { valid: false, subtitle: "No website" },
      shift: { valid: true, subtitle: "Show all fields", variables: { ...base, action: "fields" } },
      fn: primary >= 0
        ? { valid: true, subtitle: actionVerb(otherMode(mode)) + " " + primaryLabel, variables: { ...base, ...fieldVars(primary), mode: otherMode(mode) } }
        : { valid: false, subtitle: "Nothing to " + actionVerb(otherMode(mode)).toLowerCase() },
    },
  }
  if (primary < 0) item.subtitle = [item.subtitle, "↩ Show fields"].filter(Boolean).join(SEP)
  if (url && !hasCredentials(url)) item.quicklookurl = url
  return item
}

